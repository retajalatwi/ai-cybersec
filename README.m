# 🛡️ AI & Emerging Tech Security Workshop: Prompt Injection & Red Teaming

مرحباً بكم في ورشة العمل التفاعلية لتأمين التقنيات الناشئة وتطبيقات الذكاء الاصطناعي. تركز هذه الورشة على التطبيق البرمجي والمحاكاة المباشرة لتحديات الأمن السيبراني في نماذج اللغة الضخمة (LLMs).

---

## 🎯 أهداف الورشة (Workshop Objectives)
* فهم واستغلال ثغرات **Prompt Injection** و **Jailbreaking** عملياً.
* تطوير طبقات حماية ودفاع (Security Guardrails) لتأمين تطبيقات الذكاء الاصطناعي.
* اختبار استجابة النظام وتقييم مستوى الحصانة ضد الهجمات المتقدمة.

---

## 📋 تعليمات الحضور (Participant Guidelines)

### 1. المتطلبات المسبقة (Prerequisites)
* معرفة أساسية بلغة **Python**.
* حساب فعال على **GitHub** وحساب على **Google**.
* جهاز محمول مزود بمتصفح حديث (Chrome / Firefox / Edge).

### 2. بيئة العمل والتطبيق (Hands-on Environment)
لتسهيل التطبيق دون الحاجة لتثبيت أي برامج محلياً، سنعتمد على البيئة السحابية:
* اضغط على زر **Open in Colab** لتشغيل المفكرة البرمجية المباشرة.
* اختر **File > Save a copy in Drive** للبدء في كتابة الأكواد والتعديل عليها.

### 3. مسار التحدي (Challenge Roadmap)
1. **المرحلة الأولى:** تشغيل نموذج المساعد الذكي وفهم بنيته.
2. **المرحلة الثانية (Red Team):** تنفيذ هجمات هندسة الأوامر واستخراج البيانات الحساسة.
3. **المرحلة الثالثة (Blue Team):** كتابة فلتر أمني وفحص المدخلات لحماية النموذج.
4. **المرحلة الرابعة:** تقييم الحلول وإعلان النظام الأكثر حصانة.

